export interface ProjectPresetDef {
  id: string;
  label: string;
  description: string;
  create: () => {
    meta: ProjectMeta;
    enclosure: EnclosureSpec;
    rails: RailSpec[];
    items: PanelItem[];
    fieldCables: FieldCableSpec[];
    accessories: AccessoryItem[];
  };
}

function todayTr(): string {
  const d = new Date();
  return `${String(d.getDate()).padStart(2, '0')}.${String(d.getMonth() + 1).padStart(2, '0')}.${d.getFullYear()}`;
}

export function createBemisDefaultItemsWithPower(): PanelItem[] {
  return createInitialItems().map((it) => {
    if (it.category === 'mks') return { ...it, powerLossW: 5.2, unitPriceTry: 1650 };
    if (it.category === 'relay') return { ...it, powerLossW: 1.5, unitPriceTry: 420 };
    if (it.category === 'contactor') return { ...it, powerLossW: 2.5, unitPriceTry: 680 };
    if (it.category === 'terminal') return { ...it, powerLossW: 0.2, unitPriceTry: it.widthMm >= 8 ? 35 : 18 };
    if (it.category === 'button') return { ...it, powerLossW: 0.1, unitPriceTry: 210 };
    if (it.category === 'gland') return { ...it, innerPassageMm: 36, powerLossW: 0, unitPriceTry: 185 };
    return { ...it, powerLossW: 0.1, unitPriceTry: 70 };
  });
}

